/// Contract: admitted: every entry names a declared kind with exactly the
///   quantities its declared sizing takes → `Ok(CreateGenerateSuccessReturn
///   { output })`, the consumer's output, the sizes built in declared order
///   however the entries arrive.
/// Arrange: `build_create_generate_params` with `kinds` one
///   `build_vector_kind_configuration` per kind of the family mock concrete's
///   declaration in the reverse of the declared order; `concrete` left at the
///   builder's `Mock` default.
/// Act:     `create_generate`, called in the innermost consumer's method.
/// Assert:  `result.map(|success| success.output)` equals `Ok(())` by
///   `assert_eq!`.
/// Collaborators: the pairing's, hash-to-scalar's, encoding's, chain-forms',
///   kem's, key-agreement's, delivery-proof's, and random-source's mock
///   concretes in their default modes through their factories;
